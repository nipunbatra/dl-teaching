"""Practical visual evidence for Lecture 7.

The augmentation and MixUp/CutMix figures apply deterministic pixel operations
to fixed, high-resolution course-generated source photographs.  Keeping the
operations code-driven makes the comparison inspectable while avoiding the
projection-scale pixelation of the former 32x32 CIFAR-10 examples.  The measured
regularization experiment remains CIFAR-10 and is generated by the separate
``cifar_regularization_experiment.py`` script.

The MC-dropout figure is explicitly a schematic bridge, not an empirical
calibration claim.

Run from the ``dl-teaching`` repository root:

    uv run --with matplotlib --with pillow --with numpy \
      --with 'torch>=2.2' --with 'torchvision>=0.17' \
      python lecture7/diagrams/l7_practical_figs.py
"""

